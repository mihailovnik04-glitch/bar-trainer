# «ПФ» — служебная пометка «полуфабрикат», а не слово: не склоняется и не мешает
# склонять то, что за ней.
PREFIX = {'пф'}

# Латинская «e» в «Ликeр Белуга Хантинг Ягодный» — опечатка исходника. Данные не правим,
# но для поиска по словарю буквы приводим к кириллице.
LAT = str.maketrans('aeopcyxAEOPCYX', 'аеорсухАЕОРСУХ')


def _norm(w):
    return w.translate(LAT).lower().replace('ё', 'е')


# ключи словарей тоже нормализуем один раз, чтобы «ликёр» и «ликер» искались одинаково
_ADJ = {_norm(k): v for k, v in ADJ.items()}
_NOUN = {_norm(k): v for k, v in NOUN.items()}
_TAIL = {_norm(k): v for k, v in TAIL.items()}


def _keep_case(src, dst):
    """«Сироп» -> «сиропа» с сохранением заглавной, если она была."""
    return dst[:1].upper() + dst[1:] if src[:1].isupper() else dst


def genitive(name):
    """'Сироп Малина' -> 'сиропа Малина'; 'Мята' -> 'мяты'.
    None, если ведущее слово незнакомо — тогда вызывающий берёт запасную формулировку."""
    ws = (name or '').strip().split()
    if not ws:
        return None
    out, i = [], 0
    while i < len(ws) and _norm(ws[i]) in PREFIX:      # «ПФ Сахарный сироп»
        out.append(ws[i]); i += 1
    if i >= len(ws):
        return None
    lead = _norm(ws[i])
    if lead in _ADJ:                                   # «Бамбуковый лист»
        out.append(_keep_case(ws[i], _ADJ[lead])); i += 1
        if i >= len(ws) or _norm(ws[i]) not in _NOUN:
            return None                                # прилагательное без своего существительного
        out.append(_keep_case(ws[i], _NOUN[_norm(ws[i])])); i += 1
    elif lead in _NOUN:
        out.append(_keep_case(ws[i], _NOUN[lead])); i += 1
    else:
        return None
    if i < len(ws) and _norm(ws[i]) in _TAIL:          # «Брусника замороженная»
        out.append(_keep_case(ws[i], _TAIL[_norm(ws[i])])); i += 1
    out += ws[i:]                                      # бренд и уточнения — как в исходнике
    # Название целиком в нижний регистр не уводим: «сиропа Зеленое Яблоко» читается
    # как рецептура, а «Сиропа Зеленое Яблоко» — как заголовок.
    out[0] = out[0][:1].lower() + out[0][1:] if not out[0].isupper() else out[0]
    return ' '.join(out)


def how_many(unit, name):
    """Готовое начало вопроса: 'Сколько граммов мяты' либо запасное
    'Сколько граммов: «Мята»' — второе там, где склонение неизвестно."""
    u = unit_word(unit)
    g = genitive(name)
    return f'Сколько {u} {g}' if g else f'Сколько {u}: «{name}»'
